import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")


def P(*parts):
	return os.path.join(ROOT, "data", *parts)


def load(p):
	return json.load(open(p, encoding="utf-8"))


def dump(p, d):
	open(p, "w", encoding="utf-8", newline="\n").write(json.dumps(d, ensure_ascii=False, indent=1) + "\n")


def upsert(lst, items):
	ids = {x["id"] for x in items}
	return [x for x in lst if x["id"] not in ids] + items


# --- помощники для миссий --------------------------------------------------------------

def chk(name, req, tags, ok, fail, partial=""):
	d = {"name": name, "req": req, "tags": tags, "ok": ok, "fail": fail}
	if partial:
		d["partial"] = partial
	return d


def fight(name, enemies, field, ok, fail):
	return {"name": name, "combat": {"enemies": enemies, "field": field}, "tags": ["combat"], "ok": ok, "fail": fail}


def auto(name, ok):
	return {"name": name, "auto": True, "ok": ok}


def act(aid, label, text, stages, win=None, story=True, **kw):
	a = {"id": aid, "label": label, "text": text, "stages": stages}
	if story:
		a["story"] = True
	if win:
		a["on_success"] = win
	a.update(kw)
	return a


def retreat(aid, text="Отступить и вернуться позже."):
	return {"id": aid, "label": "Отступить", "text": text, "retreat": True}


def shards(n):
	return {"cmd": "adjust_resource", "resource": "shards", "value": n}


def card(c):
	return {"cmd": "add_card", "card": c}


def perm(stat, v=1, who="P01"):
	return {"cmd": "add_perm", "character": who, "stat": stat, "value": v}


def temp(stat, v, label):
	return {"cmd": "add_temp", "stat": stat, "value": v, "label": label}


def trust(a, b, v, text):
	return {"cmd": "adjust_trust", "a": a, "b": b, "value": v, "text": text}


def rum(text, tag):
	return {"text": text, "tag": tag}


def mission(mid, loc, title, briefing, arrival, rumors, threat, dur, rest, squad, actions, typ="story", **kw):
	m = {"id": mid, "location": loc, "type": typ, "title": title, "briefing": briefing, "arrival": arrival,
		"rumors": rumors, "threat": threat, "duration": dur, "rest": rest, "squad": {"min": squad[0], "max": squad[1]},
		"enemies": [], "field": "F_08", "known_tags": [], "hidden_tags": [], "context": [], "trauma_pool": "all",
		"actions": actions}
	m.update(kw)
	return m


