// Проставляет data-tip подписям полей и заголовкам внутри root.
function applyTips(root) {
  const sel = ".field > span, .section > h4, .mini-h, .detail-tabs button, .field.inline > span, .effect-form > span, .opt-head label > span";
  root.querySelectorAll(sel).forEach((el) => {
    if (el.dataset.tip) return;
    const first = [...el.childNodes].find((n) => n.nodeType === 3 && n.textContent.trim());
    const key = (first ? first.textContent : el.textContent).trim().replace(/\s*\(\d+\)$/, "");
    if (TIPS[key]) el.dataset.tip = TIPS[key];
  });
}

// Всплывающая подсказка для любых [data-tip].
(function tooltip() {
  let box = null, timer = null, cur = null;
  const hide = () => { clearTimeout(timer); cur = null; if (box) box.hidden = true; };
  document.addEventListener("mouseover", (e) => {
    const el = e.target.closest && e.target.closest("[data-tip]");
    if (el === cur) return;
    hide();
    if (!el) return;
    cur = el;
    timer = setTimeout(() => {
      if (!box) { box = document.createElement("div"); box.className = "tip"; document.body.append(box); }
      box.textContent = el.dataset.tip;
      box.hidden = false;
      const r = el.getBoundingClientRect();
      const w = Math.min(340, window.innerWidth - 20);
      box.style.maxWidth = w + "px";
      let left = Math.min(Math.max(10, r.left), window.innerWidth - box.offsetWidth - 10);
      let top = r.bottom + 8;
      if (top + box.offsetHeight > window.innerHeight - 10) top = r.top - box.offsetHeight - 8;
      box.style.left = left + "px";
      box.style.top = top + "px";
    }, 350);
  });
  document.addEventListener("mousedown", hide, true);
  document.addEventListener("scroll", hide, true);
})();
