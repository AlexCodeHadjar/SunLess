def upsert(lst, items):
	by = {x["id"]: i for i, x in enumerate(lst)}
	for it in items:
		if it["id"] in by:
			old = lst[by[it["id"]]]
			for k in ("title",):
				if k not in it and k in old:
					it[k] = old[k]
			lst[by[it["id"]]] = it
		else:
			lst.append(it)
	return lst


